def ordinal(n: int, lang: str) -> str:
    """1st, 2nd… in English; 1.ª, 2.ª… in Spanish ("tarea" is feminine)."""
    if lang == "es":
        return f"{n}.ª"
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def strings(lang: str, app: str = DEFAULT_TITLE) -> dict[str, str]:
    table = STRINGS.get(lang, STRINGS["en"])
    name = (app or DEFAULT_TITLE).strip() or DEFAULT_TITLE
    return {k: v.replace("{app}", name) for k, v in table.items()}
